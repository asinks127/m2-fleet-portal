  resolution_outcome TEXT,
  severity TEXT,
  technician_id TEXT,
  technician_name TEXT,
  assigned_repair_technician_id TEXT,
  assigned_repair_tech TEXT,
  assigned_scheduler TEXT,
  project_id TEXT,
  case_number TEXT,
  warranty_title TEXT,
  asset_number TEXT,
  site_location TEXT,
  equip_vin TEXT,
  installed_vin TEXT,
  model TEXT,
  make TEXT,
  asset_type TEXT,
  source_email_subject TEXT,
  issue_summary_clean TEXT,
  resolution_summary_clean TEXT,
  raw_email_body TEXT,
  qc_notes TEXT,
  repair_action_taken TEXT,
  repeat_issue TEXT,
  rework_required TEXT,
  has_documentation_issue TEXT,
  chargeback_risk TEXT,
  reopen_count INTEGER,
  reopened_reason TEXT,
  reopen_rate REAL,
  warranty_return_required TEXT,
  return_required TEXT,
  repair_completed_by TEXT,
  repair_completed_date TEXT,
  qc_verified_by TEXT,
  qc_verification_date TEXT,
  qc_verified TEXT,
  qc_category TEXT,
  auto_category TEXT,
  root_cause TEXT,
