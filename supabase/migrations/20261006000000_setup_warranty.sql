-- SQL to create the 5 missing warranty tables
CREATE TABLE IF NOT EXISTS warranty_claims (
  id TEXT PRIMARY KEY,
  claim_number TEXT,
  issue_description TEXT,
  resolution_date TEXT,
  technician_id TEXT,
  customer_name TEXT,
  product_description TEXT,
  resolution TEXT,
  claim_date TEXT,
  technician_name TEXT,
  return_required TEXT,
  status TEXT,
  created_date TIMESTAMP,
  updated_date TIMESTAMP,
  created_by_id TEXT,
  created_by TEXT,
  is_sample TEXT,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS technicians (
  id TEXT PRIMARY KEY,
  full_name TEXT,
  phone TEXT,
  email TEXT,
  employee_id TEXT,
  contractor_id TEXT,
  hire_date TEXT,
  training_status TEXT,
  is_active TEXT,
  specialty TEXT,
  equipment_types TEXT,
  warranty_return_count_total INTEGER,
  warranty_reopened_count INTEGER,
  repeat_issue_count INTEGER,
  open_qc_issue_count INTEGER,
  damage_claim_count INTEGER,
  most_common_issue_category TEXT,
  qc_score REAL,
  avg_days_to_close REAL,
  last_warranty_return_date TEXT,
  last_verified_warranty_date TEXT,
  created_date TIMESTAMP,
  updated_date TIMESTAMP,
  created_by_id TEXT,
  created_by TEXT,
  is_sample TEXT
);

