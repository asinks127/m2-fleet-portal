CREATE TABLE IF NOT EXISTS projects (
  id TEXT PRIMARY KEY,
  project_name TEXT,
  customer TEXT,
  project_manager TEXT,
  region TEXT,
  active_status TEXT,
  total_warranty_returns INTEGER,
  verified_warranty_returns INTEGER,
  open_warranty_returns INTEGER,
  reopened_warranty_returns INTEGER,
  most_common_issue_category TEXT,
  avg_days_to_close TEXT,
  last_warranty_return_date TEXT,
  created_date TIMESTAMP,
  updated_date TIMESTAMP,
  created_by_id TEXT,
  created_by TEXT,
  is_sample TEXT
);

CREATE TABLE IF NOT EXISTS user_sessions (
  id TEXT PRIMARY KEY,
  user_name TEXT,
  user_email TEXT,
  session_start TEXT,
  session_end TEXT,
  duration_seconds INTEGER,
  duration_minutes REAL,
  active_seconds INTEGER,
  idle_seconds INTEGER,
  is_active TEXT,
  last_seen TEXT,
  created_date TIMESTAMP,
  updated_date TIMESTAMP,
  created_by_id TEXT,
  created_by TEXT,
  is_sample TEXT
);

CREATE INDEX IF NOT EXISTS idx_warranty_claims_status ON warranty_claims(status);
CREATE INDEX IF NOT EXISTS idx_warranty_claims_technician ON warranty_claims(technician_id);
CREATE INDEX IF NOT EXISTS idx_qc_issues_status ON qc_issues(status);
CREATE INDEX IF NOT EXISTS idx_qc_issues_technician ON qc_issues(technician_id);
